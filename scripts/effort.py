#!/usr/bin/env python3
"""Proof effort: what a language costs to enter the framework, against
what one logic costs to write by hand.

Counts lines of Rocq that are neither blank nor comments. Writes
EFFORT.md; `--check` fails if EFFORT.md is out of date.
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TH = os.path.join(ROOT, "theories")

# A language's entry: its syntax, semantics and translation into the
# core. Every corner's logic and every generic rule then come with it.
LANGUAGES = [
    ("Imp (while language with havoc and choice)",
     ["Imp/Syntax.v", "Imp/BigStep.v", "Imp/Lang.v", "Core/ImpCore.v"]),
    ("Concurrent Imp (interleaving)", ["ParImp/ParImp.v"]),
    ("Adversarial language (two parties, channels)",
     ["Adversarial/AL.v", "Adversarial/Interleaving.v"]),
    ("Rely/guarantee validity (as a step relation)",
     ["ParImp/RGGenerated.v"]),
    ("Error outcomes (O'Hearn's two-outcome semantics)", ["Core/Errors.v"]),
]

# One published logic written by hand: its rules, soundness and
# completeness (and the comparison with the generated logic).
BY_HAND = [
    ("Hoare logic for Imp", ["Imp/Hoare.v"]),
    ("O'Hearn's incorrectness logic for Imp", ["Equivalence/ImpIL.v"]),
    ("Sufficient incorrectness logic for Imp", ["Equivalence/ImpSIL.v"]),
    ("Total-correctness Hoare logic for Imp", ["Equivalence/ImpTotal.v"]),
    ("O'Hearn's ok/error logic", ["Equivalence/Errors.v"]),
    ("Vanegue's adversarial logic, single thread",
     ["Equivalence/Vanegue.v"]),
    ("ILAL's interleaved adversarial logic", ["Equivalence/ILAL.v"]),
]


def strip_comments(text):
    out, depth, i = [], 0, 0
    while i < len(text):
        if text.startswith("(*", i):
            depth += 1; i += 2
        elif text.startswith("*)", i) and depth:
            depth -= 1; i += 2
        else:
            if depth == 0 or text[i] == "\n":
                out.append(text[i])
            i += 1
    return "".join(out)


def loc(files):
    n = 0
    for f in files:
        with open(os.path.join(TH, f)) as h:
            n += sum(1 for l in strip_comments(h.read()).splitlines()
                     if l.strip())
    return n


def table(rows):
    lines = ["| | Files | Lines |", "|---|---|---|"]
    for name, files in rows:
        fs = ", ".join("`" + f + "`" for f in files)
        lines.append(f"| {name} | {fs} | {loc(files)} |")
    return lines


def render():
    out = ["# Proof effort", "",
           "Generated by `python3 scripts/effort.py`. Lines of Rocq, not "
           "counting blank lines or comments.", "",
           "## Entering the framework", "",
           "A language supplies its syntax, its semantics and a translation "
           "into the core. All sixteen logics on each face, their soundness "
           "and completeness, and the generic proof rules then come with it. "
           "The files below also hold each language's worked material (rule "
           "lemmas, small examples), so they over-count the entry cost.", ""]
    out += table(LANGUAGES)
    out += ["", "## One logic, by hand", "",
            "One published logic written directly: its rules, soundness and "
            "completeness for one language and one corner, plus the "
            "comparison with the generated logic.", ""]
    out += table(BY_HAND)
    hand = [loc(f) for _, f in BY_HAND]
    entry = [loc(f) for _, f in LANGUAGES]
    avg_hand = sum(hand) // len(hand)
    out += ["", "## Comparison", "",
            f"A hand-written logic covers one corner, at about {avg_hand} lines "
            f"on average here; sixteen corners by hand would be about "
            f"{16 * avg_hand} lines per language. Entering the framework costs "
            f"{min(entry)} to {max(entry)} lines per language, once, for all "
            "sixteen corners."]
    return "\n".join(out) + "\n"


def main():
    text = render()
    path = os.path.join(ROOT, "EFFORT.md")
    if "--check" in sys.argv:
        old = open(path).read() if os.path.exists(path) else ""
        if old != text:
            sys.exit("EFFORT.md is out of date: run python3 scripts/effort.py")
        return
    with open(path, "w") as h:
        h.write(text)
    print(text)


if __name__ == "__main__":
    main()
